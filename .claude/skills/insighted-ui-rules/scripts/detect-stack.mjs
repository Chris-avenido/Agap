#!/usr/bin/env node
// Deterministic UI-stack detection. Node built-ins only. Same JSON shape for every repo.
// Usage: node detect-stack.mjs [--root <path>] [--json]
// Also imported by scan-ui-violations.mjs for walk(), config loaders and detectStack().
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const SKILL_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const SKIP_DIRS = new Set([
  'node_modules', 'dist', 'build', 'storybook-static', 'coverage', '.git', 'out', '.next', '.nuxt', '.svelte-kit',
  '.output', '.turbo', '.cache', '.parcel-cache', 'vendor', 'vendors', 'third_party', 'third-party', 'bower_components',
  'migrations', 'migration', 'migrate', 'drizzle', '.logs', '__pycache__', 'venv', '.venv', 'target', '.idea', '.vscode',
  'playwright-report', 'test-results', '__tests__', '__snapshots__',
]);
const KEEP_DOT_DIRS = new Set(['.storybook', '.agents', '.claude', '.cursor', '.github']);

export const TEMPLATE_EXTS = new Set(['.ejs', '.hbs', '.handlebars', '.pug', '.njk', '.twig', '.liquid', '.erb', '.php', '.cshtml', '.razor', '.jinja', '.jinja2', '.mustache']);
export const MARKUP_EXTS = new Set(['.html', '.htm', '.vue', '.svelte', '.astro', ...TEMPLATE_EXTS]);
export const STYLE_EXTS = new Set(['.css', '.scss', '.sass', '.less']);
export const SCRIPT_EXTS = new Set(['.ts', '.tsx', '.js', '.jsx']);
export const SCAN_EXTS = new Set([...MARKUP_EXTS, ...STYLE_EXTS, ...SCRIPT_EXTS]);
// Files whose presence proves a UI root. Plain .ts/.js alone do not (they may be backend code).
const EVIDENCE_EXTS = new Set(['.tsx', '.jsx', ...MARKUP_EXTS, ...STYLE_EXTS]);
const ROOT_MARKERS = new Set(['src', 'app', 'components', 'pages', 'views', 'templates', 'resources', 'public', 'static', 'assets', 'styles', 'layouts', 'www']);

export const posix = (p) => p.split(path.sep).join('/');
export const extOf = (f) => path.extname(f).toLowerCase();

export function isGeneratedName(name) {
  return /(?:^|[.-])generated(?:[.-]|$)/i.test(name) || /\.gen\./i.test(name) || /\.min\./i.test(name) || /\.d\.ts$/i.test(name) || /\.map$/i.test(name);
}
export function isGeneratedContent(head) {
  return /@generated|DO NOT EDIT|do not edit|auto-?generated|generated by/i.test(head.slice(0, 600));
}
export function isGeneratedPath(rel) {
  return rel.split('/').some((seg) => seg === 'generated' || seg === '__generated__');
}
export function isTestName(name) {
  return /\.(test|spec)\.[a-z]+$/i.test(name) || /\.config\.[a-z]+$/i.test(name);
}

export function walk(root, { includeDot = false } = {}) {
  const out = [];
  const stack = [''];
  while (stack.length) {
    const rel = stack.pop();
    let entries;
    try {
      entries = fs.readdirSync(path.join(root, rel), { withFileTypes: true });
    } catch {
      continue;
    }
    entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
    for (const e of entries) {
      const childRel = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) {
        if (SKIP_DIRS.has(e.name)) continue;
        if (e.name.startsWith('.') && !(includeDot && KEEP_DOT_DIRS.has(e.name))) continue;
        stack.push(childRel);
      } else if (e.isFile()) {
        out.push(childRel);
      }
    }
  }
  return out.sort();
}

export function readText(root, rel, max = 1_500_000) {
  try {
    const full = path.join(root, rel);
    if (fs.statSync(full).size > max) return '';
    return fs.readFileSync(full, 'utf8');
  } catch {
    return '';
  }
}

export function loadLibraryConfig() {
  const md = fs.readFileSync(path.join(SKILL_DIR, 'reference', 'libraries.md'), 'utf8');
  const m = md.match(/```json banned-libraries\s*\n([\s\S]*?)```/);
  if (!m) throw new Error('reference/libraries.md is missing its ```json banned-libraries block');
  return JSON.parse(m[1]);
}
export function loadTokens() {
  return JSON.parse(fs.readFileSync(path.join(SKILL_DIR, 'assets', 'insighted-tokens.json'), 'utf8'));
}

export function specMatches(spec, entry) {
  if (entry.endsWith('*')) return spec.startsWith(entry.slice(0, -1));
  return spec === entry || spec.startsWith(`${entry}/`);
}
export function firstMatch(spec, list) {
  return list.find((e) => specMatches(spec, e)) || null;
}

function git(root, args) {
  try {
    return execFileSync('git', args, { cwd: root, stdio: ['ignore', 'pipe', 'ignore'], encoding: 'utf8' }).trim();
  } catch {
    return null;
  }
}

function rootOf(rel) {
  const segs = rel.split('/').slice(0, -1);
  for (let i = 0; i < segs.length; i++) if (ROOT_MARKERS.has(segs[i])) return segs.slice(0, i + 1).join('/');
  return segs.length ? segs.join('/') : '.';
}
const isInside = (rel, folder) => folder === '.' || rel === folder || rel.startsWith(`${folder}/`);

export function detectStack(rootArg) {
  const root = path.resolve(rootArg || process.cwd());
  const files = walk(root, { includeDot: true });
  const lib = loadLibraryConfig();

  // package.json files (deps merged across workspaces)
  const packageJsonFiles = files.filter((f) => path.posix.basename(f) === 'package.json');
  const deps = new Set();
  let eslintInPackage = null;
  for (const f of packageJsonFiles) {
    try {
      const pkg = JSON.parse(readText(root, f));
      for (const k of ['dependencies', 'devDependencies', 'peerDependencies', 'optionalDependencies']) {
        for (const name of Object.keys(pkg[k] || {})) deps.add(name);
      }
      if (pkg.eslintConfig && !eslintInPackage) eslintInPackage = f;
    } catch {
      /* unreadable package.json: skip */
    }
  }
  const hasDep = (...names) => names.some((n) => deps.has(n));
  const depsMatching = (list) => [...deps].filter((d) => firstMatch(d, list)).sort();

  const extCount = {};
  for (const f of files) {
    const e = extOf(f);
    if (SCAN_EXTS.has(e)) extCount[e] = (extCount[e] || 0) + 1;
  }
  const hasExt = (set) => files.some((f) => set.has(extOf(f)));

  // framework
  const frameworks = [];
  if (hasDep('astro')) frameworks.push('astro');
  if (hasDep('svelte', '@sveltejs/kit')) frameworks.push('svelte');
  if (hasDep('vue', 'nuxt')) frameworks.push('vue');
  if (hasDep('react', 'react-dom', 'next', 'preact')) frameworks.push('react');
  if (hasDep('@angular/core')) frameworks.push('angular');
  if (hasDep('solid-js')) frameworks.push('solid');
  if (!frameworks.length) {
    if (hasExt(TEMPLATE_EXTS)) frameworks.push('server-rendered-templates');
    else if (hasExt(new Set(['.html', '.htm']))) frameworks.push('plain-html');
  }
  const framework = frameworks[0] || 'unknown';

  // UI library
  const families = lib.components.uiFamilies;
  const uiLibraryNames = Object.keys(families).filter((fam) => [...deps].some((d) => firstMatch(d, families[fam]))).sort();
  const uiLibrary = uiLibraryNames.includes('mantine') ? 'mantine' : uiLibraryNames.length ? 'other' : 'none';

  // icon and chart libraries
  const iconLibraries = depsMatching([...lib.icons.approved, ...lib.icons.banned]);
  const chartLibraries = depsMatching([...lib.charts.approved, ...lib.charts.banned, ...(lib.charts.alsoDetect || [])]);

  // CSS approach
  const cssApproaches = [];
  const tailwindConfig = files.some((f) => /(^|\/)tailwind\.config\.[cm]?[jt]s$/.test(f));
  if (hasDep('tailwindcss', '@tailwindcss/vite', '@tailwindcss/postcss') || tailwindConfig) cssApproaches.push('tailwind');
  if (hasDep('styled-components', 'styled-jsx', '@stitches/react', '@vanilla-extract/css', '@linaria/core', 'goober') || [...deps].some((d) => d.startsWith('@emotion/'))) cssApproaches.push('css-in-js');
  if (files.some((f) => /\.module\.(css|scss|sass|less)$/.test(f))) cssApproaches.push('css-modules');
  if (hasExt(STYLE_EXTS)) cssApproaches.push('plain-css');
  const cssApproach = cssApproaches[0] || 'none';

  // UI source folders
  const evidence = files.filter((f) => {
    if (!EVIDENCE_EXTS.has(extOf(f)) || f.startsWith('.') || isGeneratedName(path.posix.basename(f)) || isGeneratedPath(f)) return false;
    // A Vite/Astro-style entry index.html next to a src folder is covered by that src folder.
    if (path.posix.basename(f) === 'index.html') {
      const dir = path.posix.dirname(f);
      const prefix = dir === '.' ? 'src/' : `${dir}/src/`;
      if (files.some((g) => g.startsWith(prefix) && EVIDENCE_EXTS.has(extOf(g)))) return false;
    }
    return true;
  });
  let roots = [...new Set(evidence.map(rootOf))].sort();
  roots = roots.filter((r) => !roots.some((o) => o !== r && isInside(r, o)));
  const uiFiles = files.filter((f) => SCAN_EXTS.has(extOf(f)) && !f.startsWith('.') && !isGeneratedPath(f) && roots.some((r) => isInside(f, r)));

  // theme file candidates
  const themeNameRe = /(^|\/)(theme|themes|tokens|design-tokens|variables|colors|palette|brand)[^/]*\.(ts|tsx|js|jsx|mjs|css|scss|less|json)$/i;
  const themeDirRe = /(^|\/)(theme|themes|tokens|design-tokens)\/[^/]+\.(css|scss|less|ts|js)$/i;
  const themeSet = new Set();
  for (const f of files) {
    if (isGeneratedName(path.posix.basename(f)) || isGeneratedPath(f) || f.startsWith('.') || !roots.some((r) => isInside(f, r))) continue;
    if (themeNameRe.test(f) || themeDirRe.test(f)) {
      if (!f.startsWith('.') && !/(^|\/)(package(-lock)?|tsconfig[^/]*)\.json$/.test(f) && !/\.test\./.test(f)) themeSet.add(f);
    }
  }
  for (const f of files) {
    if (!['.ts', '.tsx', '.js', '.jsx', '.mjs'].includes(extOf(f)) || f.includes('.stories.')) continue;
    if (f.startsWith('.') || isGeneratedPath(f) || !roots.some((r) => isInside(f, r))) continue;
    if (/\b(createTheme|extendTheme|defineConfig\(\{\s*theme)\b/.test(readText(root, f, 300_000))) themeSet.add(f);
  }
  const themeFileCandidates = [...themeSet].sort();

  // Storybook
  const sbDirs = [...new Set(files.filter((f) => f.includes('.storybook/')).map((f) => f.slice(0, f.indexOf('.storybook/') + '.storybook'.length)))].sort((a, b) => a.length - b.length);
  const storybook = {
    present: sbDirs.length > 0 || [...deps].some((d) => d === 'storybook' || d.startsWith('@storybook/')),
    configPath: sbDirs[0] || null,
  };

  // ESLint
  const eslintFiles = files
    .filter((f) => /(^|\/)(eslint\.config\.[cm]?[jt]s|\.eslintrc(\.(c?js|json|ya?ml))?)$/.test(f))
    .sort((a, b) => a.split('/').length - b.split('/').length || (a < b ? -1 : 1));
  const eslintFormat = (f) =>
    /eslint\.config\./.test(f) ? 'flat' : /\.eslintrc\.c?js$/.test(f) ? 'legacy-js' : /\.eslintrc\.json$/.test(f) ? 'legacy-json' : /\.eslintrc\.ya?ml$/.test(f) ? 'legacy-yaml' : /\.eslintrc$/.test(f) ? 'legacy-json' : 'unknown';
  const eslintPath = eslintFiles[0] || eslintInPackage || null;
  const eslint = {
    present: !!eslintPath,
    configPath: eslintPath,
    format: eslintFiles[0] ? eslintFormat(eslintFiles[0]) : eslintInPackage ? 'package-json' : null,
    all: [...eslintFiles, ...(eslintInPackage ? [eslintInPackage] : [])],
  };

  // package manager
  const lock = [
    ['pnpm-lock.yaml', 'pnpm'],
    ['yarn.lock', 'yarn'],
    ['bun.lockb', 'bun'],
    ['bun.lock', 'bun'],
    ['package-lock.json', 'npm'],
  ].find(([l]) => fs.existsSync(path.join(root, l)));
  const isWindows = process.platform === 'win32';
  const pmName = lock ? lock[1] : packageJsonFiles.length ? 'npm' : 'none';
  const winExe = (n) => (isWindows && (n === 'npm' || n === 'npx' || n === 'pnpm' || n === 'yarn') ? `${n}.cmd` : n);
  const packageManager = {
    name: pmName,
    lockfile: lock ? lock[0] : null,
    runCommand: pmName === 'none' ? null : `${winExe(pmName)} run`,
    execCommand: pmName === 'npm' ? winExe('npx') : pmName === 'pnpm' ? `${winExe('pnpm')} exec` : pmName === 'yarn' ? `${winExe('yarn')} exec` : pmName === 'bun' ? 'bunx' : null,
  };

  // git
  const insideRepo = git(root, ['rev-parse', '--is-inside-work-tree']) === 'true';
  const gitInfo = {
    available: git(root, ['--version']) !== null,
    insideRepo,
    branch: insideRepo ? git(root, ['rev-parse', '--abbrev-ref', 'HEAD']) : null,
    dirty: insideRepo ? (git(root, ['status', '--porcelain']) || '').length > 0 : null,
  };

  // agent-instruction files
  const base = (f) => path.posix.basename(f);
  const agentsMd = files.filter((f) => base(f) === 'AGENTS.md');
  const claudeMd = files.filter((f) => base(f) === 'CLAUDE.md');
  const rulesFiles = files.filter((f) => /(^|\/)\.agents\/rules\/[^/]+$/.test(f));
  const agentFiles = {
    agentsMd,
    claudeMd,
    agentsRulesDirs: [...new Set(rulesFiles.map((f) => path.posix.dirname(f)))],
    agentsRulesFiles: rulesFiles,
    uiRulesFile: rulesFiles.find((f) => base(f) === 'ui.md') || null,
  };

  const profile =
    framework === 'react' && uiLibrary === 'mantine' ? 'react-mantine'
    : framework === 'react' && uiLibrary === 'other' ? 'react-other-ui'
    : framework === 'server-rendered-templates' || framework === 'plain-html' ? 'server-rendered'
    : 'other-framework';

  return {
    root: posix(root),
    framework,
    frameworks,
    uiLibrary,
    uiLibraryNames,
    iconLibraries,
    chartLibraries,
    cssApproach,
    cssApproaches,
    uiSourceFolders: roots,
    uiFileCount: uiFiles.length,
    uiFilesByExtension: Object.fromEntries(Object.entries(extCount).sort()),
    themeFileCandidates,
    storybook,
    eslint,
    packageManager,
    packageJsonFiles,
    os: { platform: process.platform, release: os.release(), isWindows },
    git: gitInfo,
    agentFiles,
    profile,
  };
}

function parseArgs(argv) {
  const args = { root: null, json: false };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--root') args.root = argv[++i];
    else if (argv[i] === '--json') args.json = true;
    else if (argv[i] === '--help' || argv[i] === '-h') args.help = true;
  }
  return args;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    console.log('node detect-stack.mjs [--root <path>] [--json]\nPrints the detected stack as JSON (pretty by default, one line with --json).');
  } else {
    try {
      const result = detectStack(args.root);
      console.log(args.json ? JSON.stringify(result) : JSON.stringify(result, null, 2));
    } catch (err) {
      console.error(`detect-stack: ${err.message}`);
      process.exitCode = 2;
    }
  }
}
