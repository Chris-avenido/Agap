#!/usr/bin/env node
// Deterministic UI checks against design tokens and generic-look tells.
// Usage: node audit-ui.mjs --src <dir> [--tokens <path>] [--changed]
// Exit code 1 if any error is found. Writes audit-report.json in the current directory.
// Craft heuristics (type range, states, surfaces, brand in layout files, tables, icon buttons, abbreviations) are
// reported in their own section. They never change the exit code, but each one must be fixed or justified.
// Craft checks only see the scanned files, so run them on the whole screen folder, not on --changed alone.
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith('--')) out[argv[i].slice(2)] = argv[i + 1] === undefined || argv[i + 1].startsWith('--') ? true : argv[++i];
  }
  return out;
}
const args = parseArgs(process.argv.slice(2));
const die = (m) => { console.error(`audit-ui: ${m}`); process.exit(2); };
if (!args.src || args.src === true) die('--src <dir> is required.');
const src = path.resolve(args.src);
if (!fs.existsSync(src) || !fs.statSync(src).isDirectory()) die(`--src is not a directory: ${src}`);
const tokensPath = path.resolve(args.tokens && args.tokens !== true ? args.tokens : path.join(process.cwd(), 'design-tokens.json'));
if (!fs.existsSync(tokensPath)) die(`tokens file not found: ${tokensPath}. Run build-theme.mjs first.`);
let tokens;
try { tokens = JSON.parse(fs.readFileSync(tokensPath, 'utf8')); } catch (e) { die(`cannot parse ${tokensPath}: ${e.message}`); }

const MARK = 'Generated by empathic-ui-redesign';
const EXT = new Set(['.css', '.scss', '.ts', '.tsx', '.js', '.jsx', '.vue', '.svelte', '.html']);
const SKIP_DIRS = new Set(['node_modules', '.git', 'dist', 'build', '.next', 'coverage', '.turbo', '.svelte-kit']);

// ---- colors
const norm = (h) => { h = h.replace('#', '').toUpperCase(); if (h.length === 3 || h.length === 4) h = [...h].map((c) => c + c).join(''); return '#' + h.slice(0, 6); };
const rgb2hex = (a) => '#' + a.map((v) => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, '0')).join('').toUpperCase();
function hsl2hex(h, s, l) {
  s /= 100; l /= 100;
  const k = (n) => (n + h / 30) % 12, a = s * Math.min(l, 1 - l);
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return rgb2hex([f(0) * 255, f(8) * 255, f(4) * 255]);
}
const allowed = new Set();
(function walkTokens(o) {
  if (typeof o === 'string' && /^#[0-9a-f]{3,8}$/i.test(o)) allowed.add(norm(o));
  else if (o && typeof o === 'object') Object.values(o).forEach(walkTokens);
})({ brand: tokens.brand, semantic: tokens.semantic, gray: tokens.gray, surface: tokens.surface, generatedScales: tokens.generatedScales, allow: tokens.audit?.allowedHex });

// ---- fonts
const fontOk = new Set(['inherit', 'initial', 'unset', 'revert']);
if (tokens.font) {
  fontOk.add(String(tokens.font.family).toLowerCase());
  String(tokens.font.fallback || '').split(',').forEach((f) => fontOk.add(f.trim().replace(/^['"]|['"]$/g, '').toLowerCase()));
}
function badFont(value) {
  if (/var\(|\$\{|theme\./.test(value)) return false;
  return value.split(',').map((f) => f.trim().replace(/^['"]|['"]$/g, '').toLowerCase()).filter(Boolean).some((f) => !fontOk.has(f));
}

// ---- contrast
function resolveColor(ref) {
  if (ref === 'white') return '#FFFFFF';
  if (ref === 'black') return '#000000';
  const parts = ref.split('.');
  const surfaceVal = (m, k) => tokens.surface?.[m]?.[k] ?? (k === 'panel' ? tokens.surface?.[m]?.card : k === 'card' ? tokens.surface?.[m]?.panel : undefined);
  let v = (parts[0] === 'light' || parts[0] === 'dark') ? surfaceVal(parts[0], parts[1]) : parts.reduce((o, k) => (o == null ? o : o[k]), tokens);
  if (typeof v === 'string' && !v.startsWith('#')) return resolveColor(v);
  return v;
}
const lum = (hex) => {
  const c = norm(hex).slice(1).match(/../g).map((x) => parseInt(x, 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

const errors = [], warnings = [];
const err = (file, line, rule, message) => errors.push({ file, line, rule, message });
const warn = (file, line, rule, message) => warnings.push({ file, line, rule, message });

for (const [a, b, min] of tokens.contrastPairs || []) {
  const ca = resolveColor(a), cb = resolveColor(b);
  if (!ca || !cb) { err(path.basename(tokensPath), 0, 'contrast-pair', `cannot resolve pair [${a}, ${b}]`); continue; }
  const got = ratio(ca, cb);
  if (got < min) err(path.basename(tokensPath), 0, 'contrast-pair', `${a} on ${b} is ${got.toFixed(2)}:1, needs ${min}:1`);
}

// ---- files
function listFiles(dir, acc = []) {
  let entries;
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch (e) { console.warn(`Cannot read directory ${dir}: ${e.message}`); return acc; }
  for (const e of entries) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (!SKIP_DIRS.has(e.name)) listFiles(p, acc); }
    else if (EXT.has(path.extname(e.name))) acc.push(p);
  }
  return acc;
}
let files = listFiles(src);
if (args.changed) {
  try {
    const run = (c) => execSync(c, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).split('\n').filter(Boolean);
    const top = execSync('git rev-parse --show-toplevel', { encoding: 'utf8' }).trim();
    const changed = new Set([...run('git diff --name-only HEAD'), ...run('git ls-files --others --exclude-standard')].map((f) => path.resolve(top, f)));
    files = files.filter((f) => changed.has(f));
  } catch { die('--changed needs a git repository.'); }
}
if (!files.length) { console.log(`No scannable files found in ${src}${args.changed ? ' (changed only)' : ''}. Nothing to audit.`); }

const shadowCount = new Map();
const cardRadii = new Map();
let scanned = 0;
const rel = (f) => path.relative(process.cwd(), f).replace(/\\/g, '/');

// ---- craft aggregation
const craft = {
  all: '', // every scanned file, generated theme files included, for presence checks
  sizes: new Set(),
  weights: new Set(),
  surfaceVars: new Set(),
  layoutFiles: [],
  brandInLayout: false,
  tableFiles: [],
  iconOnly: [],
  abbrs: new Map(),
};
const ABBR_OK = new Set(['ID', 'OK', 'AM', 'PM', 'PDF', 'URL', 'FAQ', 'UI', 'API', 'CSV', 'SMS', 'USD', 'HTML', 'CSS', 'JSON']);
const WEIGHT_CLASS = { 'font-thin': 100, 'font-light': 300, 'font-normal': 400, 'font-medium': 500, 'font-semibold': 600, 'font-bold': 700, 'font-extrabold': 800 };
const SIZE_CLASS = { 'text-xs': 12, 'text-sm': 14, 'text-base': 16, 'text-lg': 18, 'text-xl': 20, 'text-2xl': 24, 'text-3xl': 30, 'text-4xl': 36 };

function craftIngest(file, text, f) {
  craft.all += '\n' + text;
  for (const m of text.matchAll(/font-size\s*:\s*([\d.]+)(px|rem)\b/g)) craft.sizes.add(String(m[2] === 'rem' ? +m[1] * 16 : +m[1]));
  for (const m of text.matchAll(/font-size\s*:\s*var\(--font-size-(\d+)\)/g)) craft.sizes.add('scale-' + m[1]);
  for (const m of text.matchAll(/fontSize\s*[:=]\s*\{?\s*['"]?([\d.]+)(px|rem)?['"]?/g)) craft.sizes.add(String(m[2] === 'rem' ? +m[1] * 16 : +m[1]));
  for (const m of text.matchAll(/\bfz\s*=\s*\{?['"]?(\d+)/g)) craft.sizes.add(m[1]);
  for (const [c, v] of Object.entries(SIZE_CLASS)) if (new RegExp('\\b' + c + '\\b').test(text)) craft.sizes.add(String(v));
  for (const m of text.matchAll(/font-weight\s*:\s*(\d{3})/g)) craft.weights.add(m[1]);
  for (const m of text.matchAll(/font-weight\s*:\s*var\(--font-weight-([a-z0-9]+)\)/g)) craft.weights.add('scale-' + m[1]);
  for (const m of text.matchAll(/\b(?:fontWeight|fw)\s*[:=]\s*\{?['"]?(\d{3})/g)) craft.weights.add(m[1]);
  for (const [c, v] of Object.entries(WEIGHT_CLASS)) if (new RegExp('\\b' + c + '\\b').test(text)) craft.weights.add(String(v));
  for (const m of text.matchAll(/--surface-([a-z-]+)\b/g)) craft.surfaceVars.add(m[1]);
  for (const m of text.matchAll(/surface\.(?:light|dark)\.([a-zA-Z]+)/g)) craft.surfaceVars.add(m[1]);

  if (/(nav|header|sidebar|layout|shell|appbar|topbar)/i.test(path.basename(file))) {
    craft.layoutFiles.push(f);
    if (/--brand-|--semantic-interactive|color\s*=\s*["']brand["']|colors\.brand|\bbrand[.-]|primaryColor|var\(--color-primary/.test(text)) craft.brandInLayout = true;
  }
  if (/<table\b|<Table\b|<thead\b/.test(text)) craft.tableFiles.push(f);

  const lineOf = (idx) => text.slice(0, idx).split('\n').length;
  for (const m of text.matchAll(/<(button|a|ActionIcon|IconButton|UnstyledButton)\b([^>]*)>\s*<(svg|[A-Z][A-Za-z]*Icon|Fi[A-Z]\w*|Icon\w*)\b[^>]*?\/?>\s*(?:<\/\1>)?/g)) {
    const attrs = m[2];
    const before = text.slice(Math.max(0, m.index - 220), m.index);
    if (/aria-label|aria-labelledby|title\s*=|\blabel\s*=/.test(attrs) || /<Tooltip\b[^>]*$/.test(before.replace(/\n/g, ' ')) || /<Tooltip\b[^<]*$/.test(before)) continue;
    craft.iconOnly.push(`${f}:${lineOf(m.index)}`);
  }
  // number-only links and buttons (for example a rail of 01, 02, 03) need a name too
  for (const m of text.matchAll(/<(a|button|Link|NavLink)\b([^>]*)>\s*\d{1,2}\s*<\/\1>/g)) {
    if (/aria-label|aria-labelledby|title\s*=/.test(m[2])) continue;
    const before = text.slice(Math.max(0, m.index - 220), m.index);
    if (/<Tooltip\b[^<]*$/.test(before)) continue;
    craft.iconOnly.push(`${f}:${lineOf(m.index)} (number-only)`);
  }
  for (const m of text.matchAll(/>([^<>{}\n]*\b[A-Z]{2,6}\b[^<>{}\n]*)</g)) {
    const around = text.slice(Math.max(0, m.index - 160), m.index + m[0].length + 160);
    if (/title\s*=|<abbr\b|<Tooltip\b|aria-label|aria-describedby/.test(around)) continue;
    for (const t of m[1].match(/\b[A-Z]{2,6}\b/g) || []) {
      if (ABBR_OK.has(t)) continue;
      if (!craft.abbrs.has(t)) craft.abbrs.set(t, `${f}:${lineOf(m.index)}`);
    }
  }
}

for (const file of files) {
  let text;
  try { text = fs.readFileSync(file, 'utf8'); } catch (e) { warn(rel(file), 0, 'unreadable', `cannot read file: ${e.message}`); continue; }
  if (text.split('\n', 6).some((l) => l.includes(MARK))) { craft.all += '\n' + text; continue; }
  scanned++;
  craftIngest(file, text, rel(file));
  const isCss = /\.(css|scss)$/.test(file);
  const lines = text.split('\n');
  const f = rel(file);

  lines.forEach((line, i) => {
    const n = i + 1;
    if (/^\s*(\/\/|\/\*|\*)/.test(line)) return;

    // colors
    for (const m of line.matchAll(/(?<![\w&])#([0-9a-fA-F]{3,8})\b/g)) {
      if (![3, 4, 6, 8].includes(m[1].length)) continue;
      const before = line.slice(0, m.index), after = line.slice(m.index + m[0].length);
      if (/(href|to|id|htmlFor|src|from)\s*=\s*["'{`]*$/.test(before) || /url\(\s*["']?$/.test(before)) continue;
      if (isCss && !before.includes(':') && /^\s*[{,.:\[#>+~]/.test(after)) continue;
      if (!isCss && /^[\w-]*[a-zA-Z]{1}/.test(m[1]) && !/^["'`]/.test(before.slice(-1)) && !/[:(,\s]$/.test(before)) continue;
      if (!allowed.has(norm(m[0]))) err(f, n, 'off-token-color', `${m[0]} is not in the tokens`);
    }
    for (const m of line.matchAll(/\brgba?\(\s*(\d{1,3})[\s,]+(\d{1,3})[\s,]+(\d{1,3})/g)) {
      const h = rgb2hex([+m[1], +m[2], +m[3]]);
      if (!allowed.has(h)) err(f, n, 'off-token-color', `${m[0]}) (${h}) is not in the tokens`);
    }
    for (const m of line.matchAll(/\bhsla?\(\s*([\d.]+)(?:deg)?[\s,]+([\d.]+)%[\s,]+([\d.]+)%/g)) {
      const h = hsl2hex(+m[1], +m[2], +m[3]);
      if (!allowed.has(h)) err(f, n, 'off-token-color', `${m[0]}) (about ${h}) is not in the tokens`);
    }

    // fonts
    for (const m of line.matchAll(/font-family\s*:\s*([^;{}]+)/gi)) if (badFont(m[1])) err(f, n, 'off-token-font', `font-family "${m[1].trim()}" is outside the token font stack`);
    for (const m of line.matchAll(/fontFamily\s*[:=]\s*\{?\s*(['"`])(.*?)\1/g)) if (badFont(m[2])) err(f, n, 'off-token-font', `fontFamily "${m[2]}" is outside the token font stack`);
    for (const m of line.matchAll(/\bff\s*=\s*(['"])(.*?)\1/g)) if (badFont(m[2])) err(f, n, 'off-token-font', `ff "${m[2]}" is outside the token font stack`);

    // warnings
    if (/text-transform\s*:\s*uppercase|textTransform\s*[:=]\s*\{?\s*['"]uppercase|\btt\s*=\s*["']uppercase|(class(Name)?\s*=\s*["'`{][^"'`]*\buppercase\b)/.test(line)) warn(f, n, 'uppercase', 'all-caps text; use sentence case');
    if (/(linear|radial)-gradient\(/.test(line)) warn(f, n, 'gradient', 'gradient found; keep only if it carries data, not decoration');
    if (/initial\s*=\s*\{\{[^}]*opacity\s*:\s*0[^}]*\by\s*:/.test(line)) warn(f, n, 'entrance-animation', 'fade-and-slide entrance; motion should respond to an action');
    if (/>\s*0[1-9]\s*</.test(line) || /^\s*0[1-9]\s*$/.test(line) || /['"]0[1-9]['"]\s*[,}\]]/.test(line) && /(step|num|index|label|title)/i.test(line)) warn(f, n, 'numbered-marker', 'numbered marker like 01/02; use only for real sequences');
    if (/(→|&rarr;|&#8594;)\s*(<\/(button|Button|a|Link)>|['"`]\s*[,}>)])/.test(line)) warn(f, n, 'button-arrow', 'arrow appended to a button or link label');
    if (/·|&middot;|&#183;/.test(line) && !isCss) warn(f, n, 'middle-dot', 'middle-dot joined string; use separate fields or plain sentences');
    for (const m of line.matchAll(/box-shadow\s*:\s*([^;}]+)/g)) shadowCount.set(m[1].trim(), (shadowCount.get(m[1].trim()) || 0) + 1);
  });

  if (isCss) {
    for (const m of text.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
      const sel = m[1].trim(), body = m[2];
      if (/card|panel|tile/i.test(sel)) {
        const r = body.match(/border-radius\s*:\s*([^;]+)/);
        if (r) cardRadii.set(r[1].trim(), f);
        if (/:hover/.test(sel) && /(transform|translate)/.test(body)) warn(f, 0, 'hover-card', `hover motion on "${sel.slice(0, 40)}"; avoid hover transitions on every card`);
      }
    }
    for (const m of text.matchAll(/@keyframes[^{]*\{([\s\S]*?\}\s*)\}/g)) {
      if (/translateY/.test(m[1]) && /opacity/.test(m[1])) warn(f, 0, 'entrance-animation', 'keyframes combine translateY and opacity (fade-and-slide entrance)');
    }
  }
}

const craftList = [];
const cw = (file, rule, message) => craftList.push({ file, line: 0, rule, message });
if (scanned > 0) {
  if (craft.sizes.size < 4) cw('(project)', 'type-range', `only ${craft.sizes.size} distinct font-size values found (${[...craft.sizes].join(', ') || 'none'}); a screen needs at least 4 clear roles`);
  if (craft.weights.size < 3) cw('(project)', 'weight-range', `only ${craft.weights.size} distinct font-weight values found (${[...craft.weights].join(', ') || 'none'}); use at least 3`);
  if (!/:hover|\bhover:/.test(craft.all)) cw('(project)', 'no-hover', 'no :hover rules found');
  if (!/:focus-visible|\bfocus-visible:|focusRing|Mui-focusVisible/.test(craft.all)) cw('(project)', 'no-focus-visible', 'no :focus-visible styling found');
  if (!/:disabled|\[aria-disabled|\[data-disabled|\bdisabled:|Mui-disabled/.test(craft.all)) cw('(project)', 'no-disabled-style', 'no styling for :disabled or [aria-disabled] found');
  const surf = tokens.surface || {};
  for (const m of ['light', 'dark']) {
    const sm = surf[m];
    if (sm && String(sm.page).toUpperCase() === String(sm.panel ?? sm.card).toUpperCase()) cw(path.basename(tokensPath), 'flat-surfaces', `surface.${m}.page and panel resolve to the same value`);
  }
  if (craft.surfaceVars.size < 2) cw('(project)', 'one-surface', `only ${craft.surfaceVars.size} surface variable(s) used (${[...craft.surfaceVars].join(', ') || 'none'}); use page, panel and selected or raised`);
  if (craft.layoutFiles.length && !craft.brandInLayout) cw(craft.layoutFiles[0], 'brand-missing-in-chrome', `no brand color variable found in layout files (${craft.layoutFiles.slice(0, 3).join(', ')})`);
  if (craft.tableFiles.length) {
    const head = /thead[^{}]*\{[^}]*background|highlightOnHover|MuiTableHead|<thead[^>]*(style|className)/.test(craft.all);
    const hover = /tr[^{}]*:hover|highlightOnHover|MuiTableRow|hover:bg/.test(craft.all);
    if (!head) cw(craft.tableFiles[0], 'table-header', 'table markup found but no header styling (tinted thead) found');
    if (!hover) cw(craft.tableFiles[0], 'table-row-hover', 'table markup found but no row hover rule found');
  }
  for (const loc of craft.iconOnly) cw(loc, 'icon-only-unlabeled', 'icon-only button or link with no aria-label, title or tooltip');
  if (craft.abbrs.size) cw([...craft.abbrs.values()][0], 'unexplained-abbreviation', `abbreviations with no nearby title, abbr or tooltip, for review: ${[...craft.abbrs.entries()].slice(0, 12).map(([t, w]) => `${t} (${w})`).join(', ')}`);
}

for (const [v, c] of shadowCount) if (c > 5) warn('(project)', 0, 'repeated-shadow', `box-shadow "${v}" used ${c} times; prefer 1px borders`);
if (cardRadii.size > 2) warn('(project)', 0, 'card-radii', `${cardRadii.size} distinct card border-radius values (${[...cardRadii.keys()].join(', ')}); keep at most two with meaning`);

const report = { src, tokens: tokensPath, filesScanned: scanned, errorCount: errors.length, warningCount: warnings.length, craftCount: craftList.length, errors, warnings, craft: craftList };
fs.writeFileSync('audit-report.json', JSON.stringify(report, null, 2) + '\n');

console.log(`Scanned ${scanned} files in ${src}`);
const show = (title, list) => {
  if (!list.length) return;
  console.log(`\n${title} (${list.length})`);
  const byRule = {};
  list.forEach((x) => (byRule[x.rule] ||= []).push(x));
  for (const [rule, items] of Object.entries(byRule)) {
    console.log(`  ${rule}: ${items.length}`);
    items.slice(0, 8).forEach((x) => console.log(`    ${x.file}${x.line ? ':' + x.line : ''}  ${x.message}`));
    if (items.length > 8) console.log(`    ...and ${items.length - 8} more (see audit-report.json)`);
  }
};
show('ERRORS', errors);
show('WARNINGS', warnings);
show('CRAFT (fix or justify each)', craftList);
console.log(`\n${errors.length ? 'FAIL' : 'PASS'}: ${errors.length} errors, ${warnings.length} warnings, ${craftList.length} craft notes. Report: audit-report.json`);
process.exit(errors.length ? 1 : 0);
