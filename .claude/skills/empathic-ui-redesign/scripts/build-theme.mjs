#!/usr/bin/env node
// Turns design tokens into CSS variables plus a theme adapter for the detected stack.
// Surfaces: page, panel, raised, selected (a token file may still say card: it is read as panel).
// Type: type.scale becomes --font-size-N variables and drives heading sizes; type.weights become --font-weight-* variables.
// Usage: node build-theme.mjs --src <dir> [--tokens <path>] [--target css|mantine|tailwind|mui] [--out <dir>]
// Scale method (documented, fixed): 10 shades per color. Index 6 is the base color.
// Indexes 0-5 mix the base toward white by [0.92, 0.84, 0.70, 0.52, 0.30, 0.12].
// Indexes 7-9 mix the base toward black by [0.14, 0.30, 0.46].
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DEFAULTS = path.resolve(HERE, '../assets/tokens.default.json');
const MARK = 'Generated by empathic-ui-redesign build-theme.mjs. Do not edit; change design-tokens.json and rerun.';

function fail(msg) { console.error(`build-theme: ${msg}`); process.exit(1); }

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith('--')) out[argv[i].slice(2)] = argv[i + 1]?.startsWith('--') || argv[i + 1] === undefined ? true : argv[++i];
  }
  return out;
}

const hex2rgb = (h) => { h = h.replace('#', ''); if (h.length === 3) h = [...h].map((c) => c + c).join(''); return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)); };
const rgb2hex = (a) => '#' + a.map((v) => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, '0')).join('').toUpperCase();
const mix = (a, b, t) => a.map((v, i) => v + (b[i] - v) * t);
const LIGHT = [0.92, 0.84, 0.7, 0.52, 0.3, 0.12];
const DARK = [0.14, 0.3, 0.46];

function scale(hex) {
  const base = hex2rgb(hex);
  return [...LIGHT.map((t) => rgb2hex(mix(base, [255, 255, 255], t))), rgb2hex(base), ...DARK.map((t) => rgb2hex(mix(base, [0, 0, 0], t)))];
}

const isHex = (v) => typeof v === 'string' && /^#([0-9a-f]{3}|[0-9a-f]{6})$/i.test(v);

function validate(t) {
  const missing = [];
  const need = (p) => { if (p.split('.').reduce((o, k) => (o == null ? o : o[k]), t) == null) missing.push(p); };
  ['font.family', 'font.fallback', 'brand.primary', 'semantic.critical', 'semantic.attention', 'semantic.success',
    'surface.light.page', 'surface.light.text', 'surface.light.mutedText', 'surface.light.border',
    'surface.dark.page', 'surface.dark.text', 'surface.dark.mutedText', 'surface.dark.border',
    'radius.control', 'radius.panel', 'radius.table'].forEach(need);
  for (const mode of ['light', 'dark']) {
    const sm = t.surface?.[mode];
    if (sm && sm.panel == null && sm.card == null) missing.push(`surface.${mode}.panel (or card)`);
  }
  for (const k of ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900']) need(`gray.${k}`);
  if (missing.length) fail(`tokens file is missing required keys:\n  ${missing.join('\n  ')}`);
}

const normHex = (h) => String(h).replace('#', '').toUpperCase();

/** Surfaces must be told apart: light needs page, panel and selected distinct (raised may equal panel there); dark needs all four. */
function validateSurfaces(t) {
  const problems = [];
  for (const mode of ['light', 'dark']) {
    const sm = t.surface[mode];
    const names = mode === 'light' ? ['page', 'panel', 'selected'] : ['page', 'panel', 'raised', 'selected'];
    const seen = new Map();
    for (const n of names) {
      const v = normHex(n === 'panel' ? (sm.panel ?? sm.card) : sm[n]);
      if (seen.has(v)) problems.push(`surface.${mode}.${n} equals surface.${mode}.${seen.get(v)} (#${v})`);
      else seen.set(v, n);
    }
  }
  if (problems.length) fail(`surfaces are not distinct. Layering needs separate page, panel and selected colors (and raised in dark):\n  ${problems.join('\n  ')}`);
}

function validateType(t) {
  const scale = t.type?.scale;
  if (!Array.isArray(scale) || scale.length < 5 || !scale.every((n) => typeof n === 'number' && n > 0)) {
    fail('type.scale needs at least 5 positive numbers (pixel sizes), for example [12, 14, 16, 18, 24, 32].');
  }
  const weights = t.type?.weights;
  if (!Array.isArray(weights) || weights.length < 3) fail('type.weights needs at least 3 numbers, for example [400, 500, 600, 700].');
}

/** Older token files lack raised, selected and type: derive them once and write them into the file so they can be reviewed. */
function fillMissing(t) {
  const notes = [];
  const prim = hex2rgb(t.brand.primary);
  for (const mode of ['light', 'dark']) {
    const sm = t.surface?.[mode];
    const panel = sm && (sm.panel ?? sm.card);
    if (!panel) continue;
    if (sm.raised == null) {
      sm.raised = mode === 'light' ? panel : rgb2hex(mix(hex2rgb(panel), [255, 255, 255], 0.06));
      notes.push(`surface.${mode}.raised`);
    }
    if (sm.selected == null) {
      sm.selected = rgb2hex(mix(hex2rgb(panel), prim, mode === 'light' ? 0.12 : 0.28));
      notes.push(`surface.${mode}.selected`);
    }
  }
  if (t.type == null) {
    t.type = JSON.parse(fs.readFileSync(DEFAULTS, 'utf8')).type;
    notes.push('type');
  }
  return notes;
}

const camel = (s) => s.replace(/[-_ ]+(.)/g, (_, c) => c.toUpperCase());
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[_ ]+/g, '-').toLowerCase();

function detectTarget(root) {
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
    const deps = { ...pkg.dependencies, ...pkg.devDependencies };
    if (deps['@mantine/core']) return 'mantine';
    if (deps['@mui/material']) return 'mui';
    if (deps.tailwindcss) return 'tailwind';
  } catch { /* no package.json */ }
  return 'css';
}

function findRoot(src) {
  let dir = path.resolve(src);
  while (true) {
    if (fs.existsSync(path.join(dir, 'package.json'))) return dir;
    const up = path.dirname(dir);
    if (up === dir) return path.resolve(src);
    dir = up;
  }
}

const args = parseArgs(process.argv.slice(2));
if (!args.src || args.src === true) fail('--src <dir> is required (the project source directory).');
const src = path.resolve(args.src);
if (!fs.existsSync(src) || !fs.statSync(src).isDirectory()) fail(`--src is not a directory: ${src}`);

const pkgRoot = findRoot(src);
const tokensPath = path.resolve(args.tokens && args.tokens !== true ? args.tokens : path.join(process.cwd(), 'design-tokens.json'));
if (!fs.existsSync(tokensPath)) {
  fs.copyFileSync(DEFAULTS, tokensPath);
  console.log(`Created ${tokensPath} from assets/tokens.default.json. These are DEFAULT values, not the project's brand. Confirm with the user.`);
}
let tokens;
try { tokens = JSON.parse(fs.readFileSync(tokensPath, 'utf8')); } catch (e) { fail(`cannot parse ${tokensPath}: ${e.message}`); }
validate(tokens);
const filled = fillMissing(tokens);
if (filled.length) console.log(`Added missing token keys (derived, review them): ${filled.join(', ')}`);
validateSurfaces(tokens);
validateType(tokens);

const target = args.target && args.target !== true ? args.target : detectTarget(pkgRoot);
if (!['css', 'mantine', 'tailwind', 'mui'].includes(target)) fail(`unknown --target "${target}". Use css, mantine, tailwind or mui.`);
const outDir = path.resolve(args.out && args.out !== true ? args.out : path.join(src, 'theme'));

// Scales: every hex under brand (except tint) and semantic.
const scales = {};
for (const group of ['brand', 'semantic']) {
  for (const [k, v] of Object.entries(tokens[group] || {})) {
    if (isHex(v) && !(group === 'brand' && k === 'tint')) scales[`${group}.${k}`] = scale(v);
  }
}
tokens.generatedScales = scales;
fs.writeFileSync(tokensPath, JSON.stringify(tokens, null, 2) + '\n');

const colorName = (key) => (key === 'brand.primary' ? 'brand' : camel(key.split('.')[1]));
const fontStack = `'${tokens.font.family}', ${tokens.font.fallback}`;
const r = tokens.radius;
const withPanel = (sm) => {
  const o = { ...sm };
  if (o.panel == null) o.panel = o.card;
  delete o.card;
  return o;
};
const L = withPanel(tokens.surface.light);
const D = withPanel(tokens.surface.dark);
const typeScale = [...tokens.type.scale];
const typeSorted = [...typeScale].sort((a, b) => a - b);
const weightNames = { 300: 'light', 400: 'regular', 500: 'medium', 600: 'semibold', 700: 'bold', 800: 'extrabold' };
const weights = tokens.type.weights;

// tokens.css
const darkSelectors = ["[data-theme='dark']"];
if (target === 'mantine') darkSelectors.push("[data-mantine-color-scheme='dark']");
if (target === 'mui') darkSelectors.push("[data-mui-color-scheme='dark']");
if (target === 'tailwind') darkSelectors.push('.dark');
const surfaceVars = (s) => [...Object.entries(s).map(([k, v]) => `  --surface-${kebab(k)}: ${v};`), '  --surface-card: var(--surface-panel); /* alias for older code */'].join('\n');
const css = [
  `/* ${MARK} */`,
  ':root {',
  `  --font-family: ${fontStack};`,
  ...Object.entries(tokens.brand).map(([k, v]) => `  --brand-${kebab(k)}: ${v};`),
  ...Object.entries(tokens.semantic).map(([k, v]) => `  --semantic-${kebab(k)}: ${isHex(v) ? v : `var(--${v.replace('.', '-')})`};`),
  ...Object.entries(tokens.gray).map(([k, v]) => `  --gray-${k}: ${v};`),
  ...Object.entries(scales).flatMap(([k, arr]) => arr.map((v, i) => `  --${kebab(k.replace('.', '-'))}-${i}: ${v};`)),
  ...Object.entries(r).map(([k, v]) => `  --radius-${kebab(k)}: ${v}px;`),
  ...typeScale.map((v, i) => `  --font-size-${i + 1}: ${v}px;`),
  ...weights.map((w) => `  --font-weight-${weightNames[w] ?? w}: ${w};`),
  surfaceVars(L),
  '}',
  '',
  `${darkSelectors.join(',\n')} {`,
  surfaceVars(D),
  '}',
  '',
  '.tabular {',
  '  font-feature-settings: "tnum";',
  '  font-variant-numeric: tabular-nums;',
  '}',
  '',
  '@media (prefers-reduced-motion: reduce) {',
  '  *, *::before, *::after { animation-duration: 0.01ms !important; transition-duration: 0.01ms !important; }',
  '}',
  ''
].join('\n');

// Interaction states. Targets with their own component library get them through the adapter instead.
const stateCss = `
/* Interaction states (zero specificity, so any component styles win) */
:where(a, button, [role='button'], [role='switch'], summary, input, select, textarea):focus-visible {
  outline: 2px solid var(--brand-primary-6);
  outline-offset: 2px;
}
:where(button, [role='button'], a[href]):hover:where(:not(:disabled, [aria-disabled='true'])) {
  background-color: var(--surface-selected);
}
:where(:disabled, [aria-disabled='true']) {
  cursor: not-allowed;
  opacity: 0.6;
}
:where(table) { border-collapse: collapse; width: 100%; }
:where(th, td) { padding: 8px 12px; text-align: left; border-bottom: 1px solid var(--surface-border); }
:where(thead th) { background-color: var(--surface-selected); font-weight: var(--font-weight-semibold); }
:where(tbody tr):hover { background-color: var(--surface-selected); }
`;
const cssOut = target === 'css' || target === 'tailwind' ? css + stateCss : css;

const files = { 'tokens.css': cssOut };
const hdr = `// ${MARK}\n`;
const q = (a) => `[${a.map((v) => `'${v}'`).join(', ')}]`;
const grayArr = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900'].map((k) => tokens.gray[k]);
const nS = typeSorted.length;
const wBold = Math.max(...weights);
const wSemi = weights.includes(600) ? 600 : wBold;
const headings = [['h1', typeSorted[nS - 1], 1.15, wBold], ['h2', typeSorted[nS - 2], 1.2, wBold], ['h3', typeSorted[nS - 3], 1.3, wSemi], ['h4', typeSorted[nS - 4], 1.4, wSemi]];

if (target === 'mantine') {
  files['theme.ts'] = hdr + `import { createTheme, type MantineColorsTuple } from '@mantine/core';

${Object.keys(scales).map((k) => `const ${colorName(k)}: MantineColorsTuple = ${q(scales[k])};`).join('\n')}
const gray: MantineColorsTuple = ${q(grayArr)};

export const theme = createTheme({
  primaryColor: 'brand',
  colors: { ${[...Object.keys(scales).map(colorName), 'gray'].join(', ')} },
  primaryShade: { light: 6, dark: 5 },
  fontFamily: ${JSON.stringify(fontStack)},
  headings: {
    fontFamily: ${JSON.stringify(fontStack)},
    sizes: {
${headings.map(([h, s, lh, w]) => `      ${h}: { fontSize: '${s / 16}rem', lineHeight: '${lh}', fontWeight: '${w}' },`).join('\n')}
    },
  },
  defaultRadius: ${r.control},
  radius: { sm: '${r.table}px', md: '${r.control}px', lg: '${r.panel}px' },
  focusRing: 'auto', // visible keyboard focus on every control
  components: {
    Card: { defaultProps: { withBorder: true, shadow: 'none', radius: ${r.panel} }, styles: { root: { backgroundColor: 'var(--surface-panel)', borderColor: 'var(--surface-border)' } } },
    Paper: { defaultProps: { withBorder: true, shadow: 'none', radius: ${r.panel} }, styles: { root: { backgroundColor: 'var(--surface-panel)', borderColor: 'var(--surface-border)' } } },
    Button: { defaultProps: { radius: ${r.control} } },
    ActionIcon: { defaultProps: { radius: ${r.control} } },
    TextInput: { defaultProps: { radius: ${r.control} } },
    Tooltip: { defaultProps: { withArrow: true, openDelay: 150 } },
    Table: {
      defaultProps: { verticalSpacing: 'sm', withRowBorders: true, withTableBorder: true, highlightOnHover: true },
      styles: { thead: { backgroundColor: 'var(--surface-selected)' } },
    },
  },
});
`;
} else if (target === 'tailwind') {
  const keys = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900'];
  const obj = (arr) => `{ ${arr.map((v, i) => `${keys[i]}: '${v}'`).join(', ')} }`;
  files['tailwind.tokens.cjs'] = `// ${MARK}
// Use in tailwind.config: theme: { extend: require('./theme/tailwind.tokens.cjs') }
// Dark mode: set darkMode: 'class' (the .dark selector is emitted in tokens.css) or use [data-theme='dark'].
module.exports = {
  colors: {
${Object.keys(scales).map((k) => `    ${colorName(k)}: ${obj(scales[k])},`).join('\n')}
    gray: ${obj(grayArr)},
    surface: { page: 'var(--surface-page)', panel: 'var(--surface-panel)', card: 'var(--surface-panel)', raised: 'var(--surface-raised)', selected: 'var(--surface-selected)', text: 'var(--surface-text)', muted: 'var(--surface-muted-text)', border: 'var(--surface-border)' },
  },
  fontSize: { ${typeScale.map((v, i) => `'${i + 1}': '${v / 16}rem'`).join(', ')} },
  fontFamily: { sans: [${JSON.stringify(tokens.font.family)}, ${tokens.font.fallback.split(',').map((s) => JSON.stringify(s.trim().replace(/^'|'$/g, ''))).join(', ')}] },
  borderRadius: { control: '${r.control}px', panel: '${r.panel}px', table: '${r.table}px' },
};
`;
} else if (target === 'mui') {
  const crit = scales['semantic.critical'], att = scales['semantic.attention'], suc = scales['semantic.success'], pri = scales['brand.primary'];
  const palette = (s) => `{
      primary: { main: '${s === 'dark' ? pri[3] : pri[6]}', light: '${pri[3]}', dark: '${pri[8]}', contrastText: '${s === 'dark' ? D.panel : '#FFFFFF'}' },
      error: { main: '${crit[6]}' },
      warning: { main: '${att[6]}', contrastText: '${L.text}' },
      success: { main: '${suc[6]}' },
      background: { default: '${(s === 'dark' ? D : L).page}', paper: '${(s === 'dark' ? D : L).panel}' },
      text: { primary: '${(s === 'dark' ? D : L).text}', secondary: '${(s === 'dark' ? D : L).mutedText}' },
      divider: '${(s === 'dark' ? D : L).border}',
    }`;
  const states = (m) => `{
    MuiPaper: { defaultProps: { elevation: 0, variant: 'outlined' as const } },
    MuiCard: { defaultProps: { elevation: 0, variant: 'outlined' as const } },
    MuiButton: {
      defaultProps: { disableElevation: true },
      styleOverrides: {
        root: {
          '&:hover': { backgroundColor: '${m.selected}' },
          '&.Mui-focusVisible, &:focus-visible': { outline: '2px solid ${pri[6]}', outlineOffset: '2px' },
          '&.Mui-disabled': { opacity: 0.6, cursor: 'not-allowed' },
        },
      },
    },
    MuiTableHead: { styleOverrides: { root: { backgroundColor: '${m.selected}' } } },
    MuiTableCell: { styleOverrides: { head: { fontWeight: ${wSemi} }, root: { borderColor: '${m.border}' } } },
    MuiTableRow: { styleOverrides: { root: { '&:hover': { backgroundColor: '${m.selected}' } } } },
  }`;
  files['theme.ts'] = hdr + `import { createTheme } from '@mui/material/styles';

const base = {
  typography: {
    fontFamily: ${JSON.stringify(fontStack)},
${headings.map(([h, s, lh, w]) => `    ${h}: { fontSize: '${s / 16}rem', lineHeight: ${lh}, fontWeight: ${w} },`).join('\n')}
    button: { textTransform: 'none' as const, fontWeight: 600 },
  },
  shape: { borderRadius: ${r.control} },
};

export const lightTheme = createTheme({ ...base, components: ${states(L)}, palette: { mode: 'light', ...${palette('light')} } });
export const darkTheme = createTheme({ ...base, components: ${states(D)}, palette: { mode: 'dark', ...${palette('dark')} } });
`;
}

fs.mkdirSync(outDir, { recursive: true });
for (const [name, body] of Object.entries(files)) fs.writeFileSync(path.join(outDir, name), body);

console.log(`Target: ${target}`);
console.log(`Tokens: ${tokensPath} (generatedScales updated: ${Object.keys(scales).join(', ')})`);
console.log(`Wrote to ${outDir}: ${Object.keys(files).join(', ')}`);
const slug = tokens.font.family.toLowerCase().replace(/\s+/g, '-');
console.log(`\nFont "${tokens.font.family}": nothing was installed. If it is not already loaded, self-host it with font-display: swap, for example:`);
console.log(`  npm install @fontsource-variable/${slug}   (or @fontsource/${slug})`);
console.log(`  import '@fontsource-variable/${slug}';   // and import ${path.relative(process.cwd(), path.join(outDir, 'tokens.css')) || 'tokens.css'} once at the app entry`);
